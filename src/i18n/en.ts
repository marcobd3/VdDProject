const ordinal = (s: string) => {
  const v = Number(s.replace(/\D/g, ''));
  const suf = v % 100 >= 11 && v % 100 <= 13 ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' } as Record<number, string>)[v % 10] ?? 'th';
  return `${s}${suf}`;
};

